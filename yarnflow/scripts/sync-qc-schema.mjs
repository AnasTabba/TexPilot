// Copies the canonical QC v2 JSON Schema (generated from scanner/services/api/qc_schemas.py) into the Worker bundle.
// tests/qc-contract.test.mjs fails when server/qc-schema.mjs differs from the canonical file; rerun this after the schema changes.
import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../../scanner/contracts/qc-v2.schema.json', import.meta.url);
const schema = JSON.parse(await readFile(source, 'utf8'));
await writeFile(new URL('../server/qc-schema.mjs', import.meta.url), '// Generated by scripts/sync-qc-schema.mjs from scanner/contracts/qc-v2.schema.json. Do not edit.\nexport default ' + JSON.stringify(schema) + ';\n');
console.log(`QC schema synced: ${Object.keys(schema.$defs).length} definitions.`);
